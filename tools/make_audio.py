"""
Generate make_audio.bat: one TTS command per sentence used in the app.

Usage (on your PC, from the site folder):
    python tools/make_audio.py --tts-dir "C:\\SwedishTTS_Builder" --voice M1 --speed 1.1
Then run tools/make_audio.bat. It skips files that already exist, so you can
re-run it after adding new exercises — only new sentences are generated.
When it finishes, set  "audio": {"ext": "mp3"}  (or "wav") in content/manifest.json.

File names are a hash of the sentence; the site computes the same hash
(assets/js/lib/english.js → hash()), so no index file is needed.
"""
import argparse, json, os, re, unicodedata, itertools

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NONE = {'no article', 'no preposition', '', '-'}

def tidy(s):
    s = re.sub(r'\s+', ' ', s)
    s = re.sub(r'\s([.,!?])(?!\.)', r'\1', s)
    return s.strip()

def variants(q):
    if not q.get('args'):
        return [q['text']]
    args = q['args']
    combos = [[k] * len(args) for k in range(len(args[0]))] if q.get('tied') else list(itertools.product(*[range(len(a)) for a in args]))
    out = []
    for idx in combos:
        t = q['text']
        for n, lst in enumerate(args):
            t = t.replace('%' + str(n + 1), lst[idx[n]], 1)
        out.append(tidy(t))
    return out

def sentence(text, answer, qtype):
    if qtype == 'forms':
        base = re.sub(r'\s*\(.*?\)', '', text)
        return base + ', ' + answer.replace(' ', ', ', 1)
    s = re.sub(r'\s*\((?![\'"])[^)]*\)', '', text)
    if answer in NONE:
        s = re.sub(r'\s*\.\.\.\s*', ' ', s, count=1)
    else:
        s = s.replace('...', answer, 1)
    s = tidy(s)
    s = re.sub(r'^"|"$', '', s)
    return s

def jshash(s):
    h = 5381
    for ch in unicodedata.normalize('NFC', s):
        h = ((h * 33) ^ ord(ch)) & 0xFFFFFFFF
    return format(h, '08x')

def collect():
    man = json.load(open(os.path.join(ROOT, 'content', 'manifest.json'), encoding='utf8'))
    ids = man.get('modules') or [m for s in man['sections'] for m in s['modules']]
    seen = {}
    for mid in ids:
        m = json.load(open(os.path.join(ROOT, 'content', 'modules', mid + '.json'), encoding='utf8'))
        for r in m.get('rules', []):
            for ex in r.get('examples', []):
                seen.setdefault(jshash(ex), ex)
        for q in m['questions']:
            for v in variants(q):
                for a in q['answer']:
                    s = sentence(v, a, q['type'])
                    seen.setdefault(jshash(s), s)
    return seen

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tts-dir', default=r'C:\SwedishTTS_Builder', help='folder with tts_say.py')
    ap.add_argument('--engine', default='supertonic')
    ap.add_argument('--voice', default='M1')
    ap.add_argument('--speed', default='1.1')
    ap.add_argument('--lang', default='en')
    a = ap.parse_args()
    items = collect()
    with open(os.path.join(ROOT, 'tools', 'audio_list.tsv'), 'w', encoding='utf8') as f:
        for h, s in sorted(items.items(), key=lambda x: x[1]):
            f.write(f'{h}\t{s}\n')
    lines = [
        '@echo off',
        'rem Generated by tools/make_audio.py — one TTS call per sentence; existing files are skipped.',
        'chcp 65001 >nul',
        'set PYTHONUTF8=1',
        f'set "TTS_DIR={a.tts_dir}"',
        'set "OUT=%~dp0..\\assets\\audio"',
        f'set ENGINE={a.engine}', f'set VOICE={a.voice}', f'set SPEED={a.speed}', f'set LANG={a.lang}',
        'if not exist "%OUT%" mkdir "%OUT%"',
        'cd /d "%TTS_DIR%"',
        'set PY=python',
        'if exist "C:\\SwedishTTS_Builder\\.venv\\Scripts\\python.exe" set PY="C:\\SwedishTTS_Builder\\.venv\\Scripts\\python.exe"',
        'if exist ".tts_venv\\Scripts\\python.exe" set PY=".tts_venv\\Scripts\\python.exe"',
        f'echo Generating {len(items)} sentences...',
    ]
    for h, s in sorted(items.items(), key=lambda x: x[1]):
        t = s.replace('"', "'").replace('%', '%%')
        lines.append(f'if not exist "%OUT%\\{h}.mp3" if not exist "%OUT%\\{h}.wav" %PY% tts_say.py --engine %ENGINE% --voice %VOICE% --lang %LANG% --speed %SPEED% --text "{t}" -o "%OUT%\\{h}.wav"')
    lines += [
        'rem Convert to mp3 (about 10x smaller) if ffmpeg is installed',
        'where ffmpeg >nul 2>nul',
        'if %errorlevel%==0 (',
        '  for %%f in ("%OUT%\\*.wav") do ffmpeg -y -loglevel error -i "%%f" -codec:a libmp3lame -qscale:a 6 "%%~dpnf.mp3" && del "%%f"',
        '  echo Done. Set  "ext": "mp3"  in content/manifest.json',
        ') else (',
        '  echo Done. ffmpeg not found: set  "ext": "wav"  in content/manifest.json',
        ')',
        'pause',
    ]
    with open(os.path.join(ROOT, 'tools', 'make_audio.bat'), 'w', encoding='utf8', newline='\r\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(items)} sentences → tools/make_audio.bat, list in tools/audio_list.tsv')

if __name__ == '__main__':
    main()
